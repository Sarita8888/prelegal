// Pre-build codegen: reads the repo-root field-schemas.json and templates/*.md
// and writes generated TS modules the frontend imports at build/dev time.
// Run automatically via the "prebuild"/"predev"/"pretest" npm scripts.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseTemplate } from "./parseTemplate.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const FRONTEND_ROOT = join(__dirname, "..");
const REPO_ROOT = join(FRONTEND_ROOT, "..");
const OUT_DIR = join(FRONTEND_ROOT, "lib", "documents", "generated");

const fieldSchemas = JSON.parse(readFileSync(join(REPO_ROOT, "field-schemas.json"), "utf-8"));

mkdirSync(OUT_DIR, { recursive: true });

const templates = {};
let warningCount = 0;

for (const [documentType, schema] of Object.entries(fieldSchemas)) {
  const warnings = [];
  const parsedParts = schema.templateFiles.map((relativePath) =>
    parseTemplate(readFileSync(join(REPO_ROOT, relativePath), "utf-8"), schema.fields, warnings),
  );

  templates[documentType] = {
    title: parsedParts.map((part) => part.title).filter(Boolean).join(" / "),
    blocks: parsedParts.flatMap((part) => part.blocks),
  };

  for (const warning of warnings) {
    console.warn(`[build-templates] ${documentType}: ${warning}`);
    warningCount += 1;
  }
}

const banner = "// AUTO-GENERATED by frontend/scripts/build-templates.mjs — do not edit by hand.\n";

writeFileSync(
  join(OUT_DIR, "fieldSchemas.generated.ts"),
  `${banner}export const FIELD_SCHEMAS = ${JSON.stringify(fieldSchemas, null, 2)} as const;\n`,
);

writeFileSync(
  join(OUT_DIR, "templates.generated.ts"),
  `${banner}import type { ParsedTemplate } from "../templateIR";\n\n` +
    `export const TEMPLATES: Record<string, ParsedTemplate> = ${JSON.stringify(templates, null, 2)};\n`,
);

console.log(`[build-templates] wrote ${Object.keys(templates).length} document templates to ${OUT_DIR}`);
if (warningCount > 0) {
  console.warn(
    `[build-templates] completed with ${warningCount} warning(s) — some field references may not render correctly.`,
  );
}
